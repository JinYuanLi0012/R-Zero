        RUN_NAME="${MODEL_ABBR}_${RUN_VARIANT_SUFFIX:-relex_rank1}"
    else
        RUN_NAME="${MODEL_ABBR}_${RUN_VARIANT_SUFFIX:-full_delta}"
    fi
