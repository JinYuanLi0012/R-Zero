DATASET_MIN_SCORE=${DATASET_MIN_SCORE:-0.3}
DATASET_MAX_SCORE=${DATASET_MAX_SCORE:-0.8}

# Maximum elements loaded from each tensor at once by the FP32 composer.
TASK_VECTOR_CHUNK_ELEMENTS=${TASK_VECTOR_CHUNK_ELEMENTS:-8000000}
FULL_LOAD_VALIDATE=${FULL_LOAD_VALIDATE:-true}

# RELEX rank-1 trajectory. These checkpoints preserve original R-Zero's step-5 rhythm.
RANK1_HISTORY_STEPS=(5 10 15)
