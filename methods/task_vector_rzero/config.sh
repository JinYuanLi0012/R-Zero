TASK_VECTOR_SCALES=(1 1 1 1 1)

# Storage and Hugging Face. STORAGE_PATH may be exported by env_rzero.sh.
STORAGE_PATH=${STORAGE_PATH:-/data/jinyuan/rzero_storage}
